export interface NavItem {
  key: string
  label: string
  to: RouteLocationRaw
  match: string[]
  icon: string
}

export const SECTIONS: NavItem[] = [
  { key: 'races', label: 'Utrke', to: { name: 'races' }, match: ['races', 'race'], icon: ICONS.races },
  { key: 'leagues', label: 'Natjecanja', to: { name: 'leagues' }, match: ['leagues', 'league'], icon: ICONS.leagues },
  { key: 'info', label: 'Info', to: { name: 'info' }, match: ['info', 'terms'], icon: ICONS.info },
]

export function useNavItems() {
  const route = useRoute()
  const auth = useAuthStore()

  const items = computed<NavItem[]>(() => [
    ...SECTIONS,
    auth.user
      ? { key: 'profile', label: 'Profil', to: { name: 'profile' }, match: ['profile'], icon: ICONS.profile }
      : { key: 'login', label: 'Prijava', to: { name: 'login' }, match: ['login', 'signup'], icon: ICONS.profile },
  ])

  const isActive = (item: NavItem) => item.match.includes(String(route.name ?? ''))

  return { items, isActive }
}
